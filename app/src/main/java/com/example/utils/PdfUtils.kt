package com.example.utils

import android.content.Context
import android.graphics.Bitmap
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Rect
import android.graphics.pdf.PdfDocument
import java.io.File
import java.io.FileOutputStream

object PdfUtils {

    /**
     * Converts a list of Bitmaps into a multi-page PDF document.
     * Standard A4 dimensions: 595 x 842 points (72 dpi).
     */
    fun createPdfFromImages(
        context: Context,
        bitmaps: List<Bitmap>,
        filename: String = "usp_document_${System.currentTimeMillis()}.pdf",
        watermarkText: String? = null
    ): File {
        val pdfDocument = PdfDocument()
        val pageWidth = 595
        val pageHeight = 842

        bitmaps.forEachIndexed { index, bitmap ->
            val pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, index + 1).create()
            val page = pdfDocument.startPage(pageInfo)
            val canvas = page.canvas

            // Fill page background with clean white
            val bgPaint = Paint().apply { color = Color.WHITE }
            canvas.drawRect(0f, 0f, pageWidth.toFloat(), pageHeight.toFloat(), bgPaint)

            // Scale bitmap to fit page while maintaining aspect ratio
            val scale = minOf(
                (pageWidth - 40f) / bitmap.width.toFloat(),
                (pageHeight - 60f) / bitmap.height.toFloat()
            )
            val scaledWidth = bitmap.width * scale
            val scaledHeight = bitmap.height * scale
            val left = (pageWidth - scaledWidth) / 2f
            val top = (pageHeight - scaledHeight) / 2f

            val destRect = Rect(left.toInt(), top.toInt(), (left + scaledWidth).toInt(), (top + scaledHeight).toInt())
            canvas.drawBitmap(bitmap, null, destRect, null)

            // Optional Watermark
            if (!watermarkText.isNullOrBlank()) {
                val watermarkPaint = Paint().apply {
                    color = Color.argb(40, 0, 0, 0)
                    textSize = 42f
                    isAntiAlias = true
                    textAlign = Paint.Align.CENTER
                }
                canvas.save()
                canvas.rotate(-45f, pageWidth / 2f, pageHeight / 2f)
                canvas.drawText(watermarkText, pageWidth / 2f, pageHeight / 2f, watermarkPaint)
                canvas.restore()
            }

            // Header & Footer
            val textPaint = Paint().apply {
                color = Color.GRAY
                textSize = 10f
                isAntiAlias = true
            }
            canvas.drawText("Generated by UNIQUE SMART POINT", 30f, 25f, textPaint)
            canvas.drawText("Page ${index + 1} of ${bitmaps.size}", (pageWidth - 80).toFloat(), (pageHeight - 20).toFloat(), textPaint)

            pdfDocument.finishPage(page)
        }

        val outputDir = File(context.cacheDir, "pdf_exports")
        if (!outputDir.exists()) outputDir.mkdirs()
        val outputFile = File(outputDir, filename)

        FileOutputStream(outputFile).use { out ->
            pdfDocument.writeTo(out)
        }
        pdfDocument.close()
        return outputFile
    }

    /**
     * Converts formatted text (like resume, letter, or document) into a PDF file.
     */
    fun createPdfFromText(
        context: Context,
        title: String,
        bodyText: String,
        filename: String = "usp_text_doc_${System.currentTimeMillis()}.pdf"
    ): File {
        val pdfDocument = PdfDocument()
        val pageWidth = 595
        val pageHeight = 842
        val margin = 40f

        val pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, 1).create()
        val page = pdfDocument.startPage(pageInfo)
        val canvas: Canvas = page.canvas

        canvas.drawColor(Color.WHITE)

        val titlePaint = Paint().apply {
            color = Color.rgb(30, 64, 175) // Primary Blue
            textSize = 20f
            isFakeBoldText = true
            isAntiAlias = true
        }

        val bodyPaint = Paint().apply {
            color = Color.rgb(30, 41, 59)
            textSize = 12f
            isAntiAlias = true
        }

        canvas.drawText(title, margin, margin + 20f, titlePaint)

        // Draw horizontal divider
        val linePaint = Paint().apply {
            color = Color.rgb(226, 232, 240)
            strokeWidth = 2f
        }
        canvas.drawLine(margin, margin + 35f, pageWidth - margin, margin + 35f, linePaint)

        // Wrap and draw body lines
        var currentY = margin + 60f
        val lines = bodyText.split("\n")
        for (line in lines) {
            // Simple line wrapping
            val words = line.split(" ")
            var lineBuffer = ""
            for (word in words) {
                val testLine = if (lineBuffer.isEmpty()) word else "$lineBuffer $word"
                if (bodyPaint.measureText(testLine) > (pageWidth - 2 * margin)) {
                    canvas.drawText(lineBuffer, margin, currentY, bodyPaint)
                    currentY += 18f
                    lineBuffer = word
                } else {
                    lineBuffer = testLine
                }
            }
            if (lineBuffer.isNotEmpty()) {
                canvas.drawText(lineBuffer, margin, currentY, bodyPaint)
                currentY += 18f
            }
            currentY += 6f // paragraph gap
            if (currentY > pageHeight - margin - 30f) break
        }

        // Branding footer
        val footerPaint = Paint().apply {
            color = Color.GRAY
            textSize = 9f
            isAntiAlias = true
        }
        canvas.drawText("UNIQUE SMART POINT - All Your Digital Needs, One Smart Place", margin, pageHeight - 20f, footerPaint)

        pdfDocument.finishPage(page)

        val outputDir = File(context.cacheDir, "pdf_exports")
        if (!outputDir.exists()) outputDir.mkdirs()
        val outputFile = File(outputDir, filename)

        FileOutputStream(outputFile).use { out ->
            pdfDocument.writeTo(out)
        }
        pdfDocument.close()
        return outputFile
    }
}
